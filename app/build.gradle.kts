// Release signing. Create keystore.properties in the repository root (it is git-ignored)
// with storeFile, storePassword, keyAlias and keyPassword, or export RELEASE_STORE_FILE,
// RELEASE_STORE_PASSWORD, RELEASE_KEY_ALIAS and RELEASE_KEY_PASSWORD.
// Without credentials the release build is produced unsigned instead of failing.
val signingProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) {
        file.inputStream().use { load(it) }
    }
}

fun signingValue(key: String, env: String): String? =
    signingProperties.getProperty(key)?.takeIf { it.isNotBlank() }
        ?: System.getenv(env)?.takeIf { it.isNotBlank() }

// Firebase is optional at build time: drop app/google-services.json in place and
// the plugin is applied automatically. Without it the app still builds and runs
// using the bundled demo catalog.
if (file("google-services.json").exists()) {
    apply(plugin = "com.google.gms.google-services")
}

